// User-facing UI strings — single source of truth.
//
// English is authoritative: every key listed in EN is required. The
// other locales are partial — missing keys fall back to EN at
// runtime (with a dev-mode console warning). Adding a string is a
// one-line change in EN; translations follow when contributors fill
// them in.
//
// Why a hand-rolled table instead of i18next/lingui:
//   - ~170 strings total, no pluralization-heavy content
//   - one locale active at a time (no cross-fade), no dynamic load
//   - bundle budget: <30 KB gz for infra + 5 locales
//   - TS infers Key from `keyof typeof EN` so a typo is a compile error
//   - PWA precaches everything, so locale switching is instant offline
//
// NOT translated (deliberate):
//   - Pattern names (Karşılama, Bulería, Konnakol) — proper nouns
//   - Pattern stories — English baseline; per-pattern translation is
//     a separate per-PR contribution flow, not blocking i18n shipping
//   - Region IDs / tag enums — internal, never user-visible
//
// Translation quality notes:
//   - EN: native (authoritative)
//   - TR: founder is native — best-effort here, founder will refine
//   - ES: defensible (widely-used Spanish, Iberian + Latin American)
//   - ZH: simplified Chinese (zh-CN) — defensible for music tech
//   - FR: defensible
//   Music-tech terms that have universal English usage stay English
//   in every locale (BPM, MIDI, "tap", machine names like 808/909).

